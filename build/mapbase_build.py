# Builds site/assets/map-base.js: dot-matrix Korea grouped by municipality, so the
# browser can light any district and place markers from network-data.js alone.
import json, math, os
import numpy as np
from matplotlib.path import Path
import mapsvg

SP = os.path.dirname(os.path.abspath(__file__))
PROV = json.load(open(f'{SP}/mapdata/skmaps/kostat/2013/json/skorea_provinces_geo_simple.json'))
MUNI = json.load(open(f'{SP}/mapdata/skmaps/kostat/2013/json/skorea_municipalities_geo_simple.json'))
SHORT = {'11': '서울', '21': '부산', '22': '대구', '23': '인천', '24': '광주', '25': '대전', '26': '울산', '29': '세종', '31': '경기',
         '32': '강원', '33': '충북', '34': '충남', '35': '전북', '36': '전남', '37': '경북', '38': '경남', '39': '제주'}
EN = {'11': 'Seoul', '21': 'Busan', '22': 'Daegu', '23': 'Incheon', '24': 'Gwangju', '25': 'Daejeon', '26': 'Ulsan', '29': 'Sejong',
      '31': 'Gyeonggi', '32': 'Gangwon', '33': 'Chungbuk', '34': 'Chungnam', '35': 'Jeonbuk', '36': 'Jeonnam', '37': 'Gyeongbuk',
      '38': 'Gyeongnam', '39': 'Jeju'}


def merc(lon, lat):
    return lon, math.degrees(math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))


xs, ys = [], []
for f in PROV['features']:
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for p in polys:
        for lon, lat in p[0]:
            if lon < 130.5:
                x, y = merc(lon, lat); xs.append(x); ys.append(y)
minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
W = 560.0
S = W / (maxx - minx)


def P(lon, lat):
    x, y = merc(lon, lat)
    return ((x - minx) * S, (maxy - y) * S)


SX, SY, SW, SH = 196, 126, 110, 80
SC = 2.55
DX, DY = 270, 546
IW, IH = SW * SC, SH * SC

paths = []
for f in MUNI['features']:
    code = f['properties']['code']
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for p in polys:
        ring = p[0]
        if ring[0][0] > 130.5:
            continue
        paths.append((code, Path(np.array([P(lo, la) for lo, la in ring]))))


def classify(points):
    out = np.array([''] * len(points), dtype=object)
    for code, pa in paths:
        bb = pa.get_extents()
        m = (points[:, 0] >= bb.x0) & (points[:, 0] <= bb.x1) & (points[:, 1] >= bb.y0) & (points[:, 1] <= bb.y1)
        if not m.any():
            continue
        idx = np.where(m)[0]
        inside = pa.contains_points(points[idx])
        out[idx[inside]] = code
    return out


def grid(x0, y0, x1, y1, s):
    pts, r, y = [], 0, y0
    while y <= y1:
        x = x0 + ((s / 2) if r % 2 else 0)
        while x <= x1:
            pts.append((x, y)); x += s
        y += s * 0.866; r += 1
    return np.array(pts)


main = grid(2, 2, W - 2, 760 - 2, 6.4)
mc = classify(main)
box = (DX - 4, DY - 4, DX + IW + 4, DY + IH + 4)
keep = ~((main[:, 0] > box[0]) & (main[:, 0] < box[2]) & (main[:, 1] > box[1]) & (main[:, 1] < box[3]))
ig = grid(DX + 3, DY + 3, DX + IW - 3, DY + IH - 3, 4.6)
src = np.column_stack([(ig[:, 0] - DX) / SC + SX, (ig[:, 1] - DY) / SC + SY])
ic = classify(src)

muni = {}
names = {f['properties']['code']: f['properties']['name'] for f in MUNI['features']}
for code, name in names.items():
    sel = mc == code
    allpts = main[sel]
    d = ''.join(f'M{x:.1f} {y:.1f}h0' for x, y in main[sel & keep])
    di = ''.join(f'M{x:.1f} {y:.1f}h0' for x, y in ig[ic == code])
    if len(allpts):
        cx, cy = allpts[:, 0].mean(), allpts[:, 1].mean()
    else:  # tiny district: fall back to polygon centroid
        pa = [p for c, p in paths if c == code]
        v = pa[0].vertices if pa else np.array([[0, 0]])
        cx, cy = v[:, 0].mean(), v[:, 1].mean()
    inside = SX <= cx <= SX + SW and SY <= cy <= SY + SH
    muni[code] = {'n': name, 'p': code[:2], 'c': [round(cx, 1), round(cy, 1)],
                  'i': [round(DX + (cx - SX) * SC, 1), round(DY + (cy - SY) * SC, 1)] if inside else None,
                  'd': d, 'di': di}

prov = {}
for p, short in SHORT.items():
    sel = np.array([str(c)[:2] == p for c in mc])
    pts = main[sel]
    prov[p] = {'n': short, 'en': EN[p], 'c': [round(pts[:, 0].mean(), 1), round(pts[:, 1].mean(), 1)] if len(pts) else [0, 0]}

isl = mapsvg.m['islands'][0][1]
icx = sum(q[0] for q in isl) / len(isl); icy = sum(q[1] for q in isl) / len(isl)
islands = ' '.join(f'{496 + (x - icx) * 2.4:.1f},{44 + (y - icy) * 2.4:.1f}' for x, y in isl)
ix, iy = P(126.44, 37.46)
data = {'W': 560, 'H': 760, 'inset': {'x': DX, 'y': DY, 'w': round(IW, 1), 'h': round(IH, 1), 'sx': SX, 'sy': SY, 'sw': SW, 'sh': SH, 'sc': SC},
        'icn': [round(ix, 1), round(iy, 1), round(DX + (ix - SX) * SC, 1), round(DY + (iy - SY) * SC, 1)],
        'prov': prov, 'muni': muni, 'islands': islands}
js = ('/* atInc map base — generated by mapbase_build.py. Do not edit by hand. */\n'
      'window.ATMAP = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(f'{SP}/../site/assets/map-base.js', 'w', encoding='utf-8').write(js)
print('bytes', len(js.encode()), 'munis', len(muni), 'with inset', sum(1 for m in muni.values() if m['i']))
